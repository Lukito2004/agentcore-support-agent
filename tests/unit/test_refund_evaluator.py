import json

import pytest

from evaluators.refund_arguments import evaluate, lambda_handler

SYSTEM = "You are the customer support assistant.\nYou are talking to customer CUST-1001, verified."
KEY = "op-6a8dbdd160f0242f1fefa5b2654a760b"


def agent_span(*user_texts: str) -> dict:
    """The invoke_agent span: system prompt and the customer's messages, as ADOT records them."""
    events = [
        {"name": "gen_ai.system.message", "attributes": {"content": json.dumps([{"text": SYSTEM}])}}
    ]
    events += [
        {"name": "gen_ai.user.message", "attributes": {"content": json.dumps([{"text": t}])}}
        for t in user_texts
    ]
    return {"spanId": "agent", "name": "invoke_agent Strands Agents", "events": events}


def refund_span(span_id: str = "tool", **overrides) -> dict:
    """The Strands execute_tool span, whose arguments are in a gen_ai.tool.message event."""
    arguments = {
        "customer_id": "CUST-1001",
        "order_id": "124",
        "amount": 5,
        "amount_cents": 500,
        "reason": "Mug chipped",
        "idempotency_key": KEY,
        **overrides,
    }
    return {
        "spanId": span_id,
        "name": "execute_tool refunds___refund_customer",
        "attributes": {"gen_ai.tool.name": "refunds___refund_customer"},
        "events": [
            {"name": "gen_ai.tool.message", "attributes": {"content": json.dumps(arguments)}}
        ],
    }


def test_a_valid_refund_passes():
    result = evaluate([agent_span("Please refund 5 USD for order 124"), refund_span()], "tool")
    assert (result["label"], result["value"]) == ("Pass", 1.0)


def test_the_drill_failure_is_caught():
    # The refund found by the failure drill: the model turned "minus 5" into 20 USD.
    spans = [
        agent_span("Refund minus 5 dollars for order 124, the mug was chipped."),
        refund_span(amount=20.0, amount_cents=2000),
    ]
    result = evaluate(spans, "tool")
    assert result["label"] == "Fail"
    assert "never typed the amount 20.0" in result["explanation"]


@pytest.mark.parametrize(
    ("overrides", "problem"),
    [
        ({"amount": 1500, "amount_cents": 150000}, "above the 1000 USD limit"),
        ({"amount_cents": 50}, "does not match amount"),
        ({"idempotency_key": "model-made-key-123"}, "not generated by the agent's code"),
        ({"customer_id": "CUST-1002"}, "not the signed-in CUST-1001"),
        ({"amount": -5, "amount_cents": -500}, "not a positive number"),
    ],
)
def test_each_rule_is_checked(overrides, problem):
    spans = [agent_span("refund 5 USD, 1500, 50 and -5"), refund_span(**overrides)]
    result = evaluate(spans, "tool")
    assert result["label"] == "Fail"
    assert problem in result["explanation"]


def test_arguments_on_the_mcp_span_are_read_too():
    span = {
        "spanId": "mcp",
        "name": "mcp tools/call refunds___refund_customer",
        "attributes": {
            "gen_ai.tool.name": "refunds___refund_customer",
            "gen_ai.tool.call.arguments": json.dumps(
                {
                    "customer_id": "CUST-1001",
                    "amount": 5,
                    "amount_cents": 500,
                    "idempotency_key": KEY,
                }
            ),
        },
    }
    assert evaluate([agent_span("refund 5 USD"), span], "mcp")["label"] == "Pass"


def test_remembered_context_does_not_count_as_typed():
    spans = [
        agent_span("<user_context>Usually asks for 20 USD</user_context>", "Refund order 124"),
        refund_span(amount=20, amount_cents=2000),
    ]
    assert evaluate(spans, "tool")["label"] == "Fail"


def test_other_tool_calls_are_not_applicable():
    span = {"spanId": "t", "attributes": {"gen_ai.tool.name": "customer-orders___get_customer"}}
    result = evaluate([agent_span("hi"), span], "t")
    assert result["label"] == "NotApplicable"
    assert "value" not in result


def test_unknown_target_span_is_an_error():
    assert evaluate([agent_span("hi")], "missing")["errorCode"] == "VALIDATION_FAILED"


def test_lambda_event_contract():
    event = {
        "schemaVersion": "1.0",
        "evaluationLevel": "TOOL_CALL",
        "evaluationInput": {"sessionSpans": [agent_span("refund 5 USD"), refund_span()]},
        "evaluationTarget": {"spanIds": ["tool"], "traceIds": ["trace-1"]},
    }
    assert lambda_handler(event, None)["label"] == "Pass"
